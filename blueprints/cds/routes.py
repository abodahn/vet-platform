"""
Clinical Decision Support (CDS) — Aleefy Platform
=================================================

Species contraindications, drug-drug interactions and weight-based dose ranges.

WHAT THIS MODULE IS
-------------------
A deterministic rule engine over ONE curated, cited, human-reviewable data file
(``drug_data.json``, sitting next to this file). Every clinical fact shown to a
user comes from that file. Nothing is generated by a language model at runtime,
so the module works with the AI service switched off, offline, or unreachable.

WHAT THIS MODULE IS NOT
-----------------------
It is not authoritative and it is not complete. See ``_KNOWN_GAPS`` in the data
file. Absence of a warning NEVER means "safe" — an unrecognised drug produces a
loud ``unverified`` alert instead of silence.

The engine (everything above the "Flask routes" banner) is pure: no database, no
network, no Flask context. It is unit-testable on its own — see
``tests/test_cds.py``.
"""

