def _parse_drugs(value):
    """Accept a JSON list, or newline/comma-separated free text from the form."""
    if isinstance(value, (list, tuple)):
        return [str(v) for v in value]
    return [p for p in re.split(r"[\n,;]+", str(value or ""))]


def _result_json(result):
    out = dict(result)
    out["alerts"] = [a.to_dict() for a in result["alerts"]]
    out["doses"] = [d.to_dict() for d in result["doses"]]
    return out


@cds_bp.route("/", methods=["GET", "POST"])
@login_required
def index():
    """Standalone manual checker. Server-rendered — works without JavaScript."""
    result = None
    form = {"drugs": "", "species": "", "breed": "", "weight_kg": ""}
    if request.method == "POST":
        form = {
            "drugs": request.form.get("drugs", ""),
            "species": request.form.get("species", ""),
            "breed": request.form.get("breed", ""),
            "weight_kg": request.form.get("weight_kg", "").strip(),
        }
        # Rendered from the plain-dict form so the template sees the same shape
        # the JSON endpoint returns — one representation, not two.
        result = _result_json(screen(
            _parse_drugs(form["drugs"]), form["species"],
            form["breed"] or None, form["weight_kg"] or None,
        ))
    return render_template(
        "cds/index.html", active="cds", form=form, result=result,
        severity_rank=SEVERITY_RANK, severity_label=SEVERITY_LABEL,
        advisory=ADVISORY, data_version=DATA_VERSION, review_status=REVIEW_STATUS,
    )


@cds_bp.route("/api/screen", methods=["POST"])
@login_required
def api_screen():
    """JSON screen. Callable from the visits / pharmacy prescribing flows.

    POST {"drugs": ["Metacam 1.5mg/ml", "Prednisolone"], "species": "Cat",
          "breed": "Persian", "weight_kg": "4.2"}

    Send the CSRF token in the X-CSRF-Token header (app.py validates every
    non-GET request). Response mirrors screen() with alerts sorted worst-first.
    """
    data = request.get_json(silent=True) or {}
    result = screen(
        _parse_drugs(data.get("drugs")),
        data.get("species", ""),
        data.get("breed") or None,
        data.get("weight_kg") or None,
    )
    return jsonify(_result_json(result))


@cds_bp.route("/api/dose", methods=["POST"])
@login_required
def api_dose():
    """JSON dose calculation for a single drug. Refuses rather than extrapolates."""
