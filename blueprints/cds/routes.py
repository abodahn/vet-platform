def check_contraindications(drug: str, species: str, breed: str = None) -> list:
    """Species- and breed-specific 'do not give' rules for a single drug."""
    alerts = []
    match = resolve_drug(drug)
    sp = resolve_species(species)

    if not match.ok:
        return [_unknown_drug_alert(drug)]

    if match.reason == "combination":
        alerts.append(Alert(
            severity=INFO, kind="lookup", drugs=[drug],
            message_en=("Read as a combination product containing: "
                        + ", ".join(match.canonicals)
                        + ". Each component was screened separately — confirm this is correct."),
            message_ar=("تمت قراءته كمستحضر مركّب يحتوي على: "
                        + "، ".join(match.canonicals)
                        + ". فُحص كل مكوّن على حدة — يُرجى التأكد من صحة ذلك."),
        ))

    if sp is None:
        alerts.append(Alert(
            severity=UNVERIFIED, kind="lookup", drugs=[drug], species=species,
            message_en=(f'Species "{species or "(blank)"}" was not recognised, so NO '
                        f"species contraindication check was performed. Species-specific "
                        f"lethality is the most important check this tool does — set the "
                        f"species on the patient record and re-run."),
            message_ar=(f'لم يتم التعرف على النوع "{species or "(فارغ)"}"، لذلك لم يُجرَ أي '
                        f"فحص لموانع الاستعمال حسب النوع. يُرجى ضبط نوع الحيوان في ملف "
                        f"المريض وإعادة الفحص."),
        ))
        return alerts

    breed_clean = _basic_clean(breed)

    for canonical in match.canonicals:
        for entry in DATA["species_contraindications"]:
            if _drug_in(entry["drug"], canonical) and sp in entry["species"]:
                alerts.append(Alert(
                    severity=entry["severity"], kind="contraindication",
                    drugs=[drug], species=sp,
                    message_en=entry["effect"]["en"], message_ar=entry["effect"]["ar"],
                    alternative_en=entry.get("alternative", {}).get("en", ""),
                    alternative_ar=entry.get("alternative", {}).get("ar", ""),
                    source=entry["source"],
                ))

        for entry in DATA["breed_contraindications"]:
            if not (_drug_in(entry["drug"], canonical) and sp in entry["species"]):
                continue
            # Both sides through _basic_clean: the typed breed is stripped of
            # punctuation, so a rule string like "long-haired whippet" could
            # never match "Long-haired Whippet" while only one side was cleaned.
            hit = ([b for b in entry["breeds"] if _basic_clean(b) in breed_clean]
                   if breed_clean else [])
            if hit:
                alerts.append(Alert(
                    severity=entry["severity"], kind="breed",
                    drugs=[drug], species=sp,
                    message_en=(f"Breed \"{breed}\" is on the at-risk list "
                                f"({entry.get('gene') or 'breed predisposition'}). "
                                + entry["effect"]["en"]),
                    message_ar=(f"السلالة \"{breed}\" ضمن السلالات المعرّضة للخطر "
                                f"({entry.get('gene') or 'استعداد سلالي'}). "
                                + entry["effect"]["ar"]),
                    alternative_en=entry.get("alternative", {}).get("en", ""),
                    alternative_ar=entry.get("alternative", {}).get("ar", ""),
                    source=entry["source"],
                ))
            elif not breed_clean:
                alerts.append(Alert(
                    severity=CAUTION, kind="breed", drugs=[drug], species=sp,
                    message_en=(f"No breed recorded for this patient. {canonical} has a "
                                f"breed-specific contraindication "
                                f"({entry.get('gene') or 'breed predisposition'}) — "
                                f"confirm the breed before prescribing."),
                    message_ar=(f"لم تُسجَّل سلالة هذا المريض. للدواء {canonical} مانع استعمال "
                                f"مرتبط بالسلالة — يجب تأكيد السلالة قبل الوصف."),
                    source=entry["source"],
                ))

    return sorted(alerts, key=lambda a: a.rank)


def check_interactions(drug_list) -> list:
    """Pairwise interaction screen over a list of drug names."""
    alerts = []
    matches = [resolve_drug(d) for d in (drug_list or []) if str(d).strip()]

    for m in matches:
        if not m.ok:
            alerts.append(_unknown_drug_alert(m.raw))

    resolved = [m for m in matches if m.ok]

    # Same active ingredient prescribed twice (e.g. a trade name and a generic).
    seen = {}
    for m in resolved:
        for canonical in m.canonicals:
            if canonical in seen and seen[canonical] != m.raw:
                alerts.append(Alert(
                    severity=MAJOR, kind="interaction",
                    drugs=[seen[canonical], m.raw],
                    message_en=(f'"{seen[canonical]}" and "{m.raw}" are both {canonical} — '
                                f"duplicate therapy. The patient would receive a double dose."),
                    message_ar=(f'"{seen[canonical]}" و"{m.raw}" كلاهما {canonical} — '
                                f"ازدواج علاجي؛ سيتلقى المريض ضعف الجرعة."),
                ))
            seen.setdefault(canonical, m.raw)

    # Only worth saying when an interaction screen actually happened.
    if len(resolved) > 1:
        for m in resolved:
            for canonical in m.canonicals:
                cls, covered = _CLASS_GAPS.get(canonical, (None, None))
                if not cls:
                    continue
                alerts.append(Alert(
                    severity=CAUTION, kind="lookup", drugs=[m.raw],
                    message_en=(f"{canonical} is in the {cls} class, but no interaction "
                                f"rule in this dataset is written against that class — "
                                f"only against {', '.join(covered)} individually. The "
                                f"interactions recorded for those drugs have NOT been "
                                f"checked for {canonical}. Check them manually."),
                    message_ar=(f"ينتمي {canonical} إلى فئة {cls}، لكن لا توجد في هذه "
                                f"البيانات قاعدة تداخل مكتوبة على مستوى الفئة — بل على "
                                f"أدوية بعينها ({'، '.join(covered)}). لم تُفحص التداخلات "
                                f"المسجَّلة لتلك الأدوية بالنسبة لـ {canonical} — يجب "
                                f"مراجعتها يدويًا."),
                ))

    for i in range(len(resolved)):
        for j in range(i + 1, len(resolved)):
            a, b = resolved[i], resolved[j]
            for ca in a.canonicals:
                for cb in b.canonicals:
                    for entry in DATA["interactions"]:
                        k1, k2 = entry["drugs"]
                        forward = _drug_in(k1, ca) and _drug_in(k2, cb)
                        reverse = _drug_in(k1, cb) and _drug_in(k2, ca)
                        if not (forward or reverse):
                            continue
                        if k1 == k2 and ca == cb:
                            continue  # a class-vs-itself rule needs two different members
                        alerts.append(Alert(
                            severity=entry["severity"], kind="interaction",
                            drugs=[a.raw, b.raw],
                            message_en=entry["effect"]["en"],
                            message_ar=entry["effect"]["ar"],
                            source=entry["source"],
                        ))

    # De-duplicate: the same rule can fire twice via a class and a member.
    unique, keys = [], set()
    for al in alerts:
        key = (al.severity, al.kind, tuple(sorted(al.drugs)), al.message_en[:80])
        if key not in keys:
            keys.add(key)
            unique.append(al)
    return sorted(unique, key=lambda a: a.rank)


def _dec(value):
    """Parse a caller-supplied number, or None if it is not one the engine can
    compute on. "nan" and "inf" parse cleanly and then raise InvalidOperation on
    the first comparison or quantize; a magnitude past the working precision
    cannot be rounded for display and would render millions of digits. Both are
    rejected here rather than reaching the arithmetic — a 500 is not a refusal.
    """
    try:
        d = Decimal(str(value).strip())
    except (InvalidOperation, AttributeError, ValueError):
        return None
    return d if d.is_finite() and d.adjusted() < getcontext().prec else None


def _fmt(d: Decimal) -> str:
    """Trim a Decimal for display without going anywhere near float."""
    try:
        d = d.quantize(Decimal("0.0001"))
    except InvalidOperation:
        pass    # more digits than the context can round — print it whole, not 500
    return format(d.normalize(), "f")


# No animal a veterinary clinic treats weighs more than this. The bound is
# about catching a typed extra zero, not about zoology.
MAX_BODY_WEIGHT_KG = 2000


def calculate_dose(drug: str, species: str, weight_kg, breed: str = None) -> DoseResult:
    """Weight-based dose range for one drug in one patient.

    Refuses rather than extrapolates: an unknown drug, an unknown species, a
    drug/species pair with no entry, or a drug that is contraindicated in this
    patient all return ok=False with a reason.
    All arithmetic is Decimal — a rounding error here has physical consequences.
    """
    match = resolve_drug(drug)
    sp = resolve_species(species)
    weight = _dec(weight_kg)

    def refuse(en, ar, alerts=None):
        return DoseResult(ok=False, drug=drug, species=species,
                          canonical=match.canonicals[0] if match.ok else None,
                          refusal_en=en, refusal_ar=ar, alerts=alerts or [])

    if not match.ok:
        return refuse(
            f'"{drug}" is not in the clinical database, so no dose can be calculated. '
            f"Never extrapolate a dose from another drug or another species.",
            f'الدواء "{drug}" غير موجود في قاعدة البيانات، ولا يمكن حساب الجرعة. '
            f"لا يجوز إطلاقًا اشتقاق الجرعة من دواء آخر أو نوع آخر.",
            [_unknown_drug_alert(drug)],
        )
    if match.reason == "combination":
        return refuse(
            f'"{drug}" was read as a combination product ({", ".join(match.canonicals)}). '
            f"Dose each active ingredient separately from the product label.",
            f'تمت قراءة "{drug}" كمستحضر مركّب ({"، ".join(match.canonicals)}). '
            f"يجب حساب جرعة كل مادة فعّالة على حدة من نشرة المستحضر.",
        )
    if sp is None:
        return refuse(
            f'Species "{species or "(blank)"}" is not recognised. Dose ranges are '
            f"species-specific and are never carried across species.",
            f'النوع "{species or "(فارغ)"}" غير معروف. مدى الجرعات يختلف حسب النوع '
            f"ولا يُنقل بين الأنواع.",
        )
    # Before any number is produced. A dose card printed under a DO NOT GIVE
    # card reads as an instruction; the guard belongs here rather than in the
    # template so /api/dose cannot serve one either.
    blocked = [a for a in check_contraindications(drug, species, breed)
               if a.severity == CONTRAINDICATED]
    if blocked:
        return refuse(
            f'"{drug}" is contraindicated in this patient, so no dose is calculated. '
            f"A drug that must not be given has no safe dose.",
            f'الدواء "{drug}" ممنوع الإعطاء لهذا المريض، لذلك لم تُحسب أي جرعة. '
            f"الدواء الممنوع ليس له جرعة آمنة.",
            blocked,
        )
    # An upper bound as well as a lower one. Removing the crash on an absurd
    # weight is only half the fix: 1e24 kg stopped raising and started
    # returning 1e23 mg as a real dose card, which is worse than an error -
    # an error is obviously wrong, a printed number looks considered.
    # 2000 kg clears every patient a mixed practice sees, a draught horse
    # included, and a typed extra zero above that is a slip, not a patient.
    if weight is None or weight <= 0 or weight > MAX_BODY_WEIGHT_KG:
        return refuse(
            f'Weight "{weight_kg}" is not a usable body weight in kg.',
            f'الوزن "{weight_kg}" غير صالح كوزن جسم بالكيلوجرام.',
        )

    canonical = match.canonicals[0]
    row = next((r for r in DATA["doses"]
                if r["drug"] == canonical and r["species"] == sp), None)
    if row is None:
        return refuse(
            f"No dose entry for {canonical} in {sp}. This tool will not extrapolate a "
            f"dose from another species — use a current formulary.",
            f"لا توجد جرعة مسجلة لـ {canonical} في {sp}. لن تُشتق الجرعة من نوع آخر — "
            f"يُرجى الرجوع إلى مرجع دوائي حديث.",
        )

    alerts = []
    rng = _WEIGHT_RANGES.get(sp)
    if rng:
        low, high = _dec(rng["min"]), _dec(rng["max"])
        if weight < low or weight > high:
            alerts.append(Alert(
                severity=MAJOR, kind="dose", drugs=[drug], species=sp,
                message_en=(f"{weight_kg} kg is outside the plausible weight range for a "
                            f"{sp} ({rng['min']}-{rng['max']} kg). Check the weight and the "
                            f"units before giving this dose — a mis-keyed weight is a "
                            f"common cause of overdose."),
                message_ar=(f"الوزن {weight_kg} كجم خارج المدى المنطقي لهذا النوع ({sp}: "
                            f"{rng['min']}-{rng['max']} كجم). تحقق من الوزن ووحدته قبل "
                            f"الإعطاء — خطأ إدخال الوزن سبب شائع لفرط الجرعة."),
            ))

    min_pk, max_pk = _dec(row["min_per_kg"]), _dec(row["max_per_kg"])
    max_daily_pk = _dec(row.get("max_per_kg_per_day"))

    return DoseResult(
        ok=True, drug=drug, species=species, canonical=canonical,
        weight_kg=_fmt(weight), unit=row["unit"],
        min_total=_fmt(min_pk * weight),
        max_total=_fmt(max_pk * weight),
        max_daily_total=_fmt(max_daily_pk * weight) if max_daily_pk is not None else None,
        per_kg_range=(f"{row['min_per_kg']}-{row['max_per_kg']} {row['unit']}/kg"
                      if row["min_per_kg"] != row["max_per_kg"]
                      else f"{row['min_per_kg']} {row['unit']}/kg"),
        frequency=row.get("frequency", ""), route=row.get("route", ""),
        note_en=row.get("note", {}).get("en", ""),
        note_ar=row.get("note", {}).get("ar", ""),
        source=row["source"], alerts=alerts,
    )


def screen(drugs, species, breed=None, weight_kg=None) -> dict:
    """Full screen for a prescription: contraindications + interactions + doses."""
    drugs = [str(d).strip() for d in (drugs or []) if str(d).strip()]
    alerts = []
    for d in drugs:
        alerts.extend(check_contraindications(d, species, breed))
    alerts.extend(check_interactions(drugs))

    # Same alert can arrive from two drugs in a combination product.
    unique, keys = [], set()
    for al in alerts:
        key = (al.severity, al.kind, tuple(sorted(al.drugs)), al.message_en[:80])
        if key not in keys:
            keys.add(key)
            unique.append(al)
    unique.sort(key=lambda a: a.rank)

    doses = [calculate_dose(d, species, weight_kg, breed) for d in drugs] if weight_kg else []

    return {
        "drugs": drugs,
        "species": species,
        "breed": breed,
        "weight_kg": weight_kg,
        "alerts": unique,
        "doses": doses,
        "worst_severity": unique[0].severity if unique else None,
        "checked_count": len(drugs),
        "unrecognised": [m.raw for m in (resolve_drug(d) for d in drugs) if not m.ok],
        "advisory": ADVISORY,
        "data_version": DATA_VERSION,
        "review_status": REVIEW_STATUS,
    }


