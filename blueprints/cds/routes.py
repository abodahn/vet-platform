@dataclass
class Alert:
    """One thing the prescriber needs to know. Never constructed from AI output."""
    severity: str
    kind: str                      # contraindication | breed | interaction | dose | lookup
    drugs: list                    # display names, as the user typed them
    message_en: str
    message_ar: str
    species: Optional[str] = None
    alternative_en: str = ""
    alternative_ar: str = ""
    source: str = ""

    @property
    def rank(self):
        return SEVERITY_RANK.get(self.severity, 9)

    def to_dict(self):
        d = asdict(self)
        d["severity_label"] = SEVERITY_LABEL.get(self.severity, SEVERITY_LABEL[INFO])
        return d


@dataclass
class DoseResult:
    ok: bool
    drug: str                       # as supplied
    species: str                    # as supplied
    canonical: Optional[str] = None
    weight_kg: Optional[str] = None
    unit: str = "mg"
    min_total: Optional[str] = None     # per administration, for this patient
    max_total: Optional[str] = None
    max_daily_total: Optional[str] = None
    per_kg_range: str = ""
    frequency: str = ""
    route: str = ""
    note_en: str = ""
    note_ar: str = ""
    source: str = ""
    refusal_en: str = ""
    refusal_ar: str = ""
    alerts: list = field(default_factory=list)

    def to_dict(self):
        d = asdict(self)
        d["alerts"] = [a.to_dict() if isinstance(a, Alert) else a for a in self.alerts]
        return d


# ═════════════════════════════════════════════════════════════════════════════
#  Name matching
#
#  Deliberately EXACT, never fuzzy. Inventory rows are trade names with
#  strengths, dosage forms and sometimes Arabic ("Synulox 250mg Tablets",
#  "باراسيتامول 500 مجم"). We strip the packaging noise and then require an
#  exact hit in the alias table. A near-miss produces an `unverified` alert, not
#  a guess: a wrong match that silently fails to warn is the dangerous outcome,
#  and edit-distance matching would confuse e.g. prednisone/prednisolone and
#  amikacin/amoxicillin.
# ═════════════════════════════════════════════════════════════════════════════

# Packaging / formulation noise. Removed before matching.
_NOISE = {
    "mg", "mcg", "ug", "gm", "gr", "iu", "ml", "l", "kg", "cc", "unit", "units",
    "tab", "tabs", "tablet", "tablets", "cap", "caps", "capsule", "capsules",
    "susp", "suspension", "syrup", "solution", "soln", "sol", "elixir",
    "inj", "injection", "injectable", "vial", "ampoule", "amp", "amps",
    "cream", "ointment", "gel", "paste", "powder", "sachet", "drops", "drop",
    "spray", "collar", "shampoo", "chew", "chewable", "chews", "flavour",
    "flavor", "flavoured", "flavored", "spot", "spoton", "topical",
    "oral", "po", "sc", "iv", "im", "otm", "sq",
    "for", "and", "plus", "with", "the", "per", "pack", "box", "strip",
    "dog", "dogs", "cat", "cats", "puppy", "puppies", "kitten", "kittens",
    "small", "medium", "large", "extra", "forte", "vet", "veterinary",
    "بيطري", "أقراص", "اقراص", "قرص", "شراب", "حقن", "مجم", "مل", "معلق",
    "للكلاب", "للقطط", "كبسولات", "مرهم",
}

_NUMERIC = re.compile(r"^[\d.,/x×+-]+[a-z%]*$")
_NON_WORD = re.compile(r"[^0-9a-z؀-ۿ%]+")


def _basic_clean(raw: str) -> str:
    """Lowercase and drop punctuation. Nothing else — used for species and breed,
    where the drug noise list would eat the actual word ("cat", "dog")."""
    if not raw:
        return ""
    return " ".join(_NON_WORD.sub(" ", str(raw).lower()).split())


def clean_name(raw: str) -> str:
    """Lowercase, drop punctuation, strengths and dosage-form words. Drugs only."""
    tokens = [
        tok for tok in _basic_clean(raw).split()
        if tok not in _NOISE and not _NUMERIC.match(tok)
    ]
    return " ".join(tokens)


@dataclass
class DrugMatch:
    raw: str
    canonicals: list          # 0 = unknown, 1 = confident, >1 = combination product
    reason: str               # matched | combination | unknown | empty

    @property
    def ok(self):
        return bool(self.canonicals)


def resolve_drug(raw: str) -> DrugMatch:
    """Map a free-text / inventory drug name onto canonical keys.

    Longest n-gram wins, so "amoxicillin clavulanic acid" resolves to the
    combination product rather than to plain amoxicillin. If several distinct
    canonical drugs match at that length the name is treated as a COMBINATION
    product and all of them are screened — over-warning is the safe direction.
    """
    cleaned = clean_name(raw)
    if not cleaned:
        return DrugMatch(raw, [], "empty")

    tokens = cleaned.split()
    for n in range(min(_MAX_ALIAS_TOKENS, len(tokens)), 0, -1):
        hits = []
        for i in range(len(tokens) - n + 1):
            canonical = _ALIASES.get(" ".join(tokens[i:i + n]))
            if canonical and canonical not in hits:
                hits.append(canonical)
        if hits:
            return DrugMatch(raw, hits, "matched" if len(hits) == 1 else "combination")

    return DrugMatch(raw, [], "unknown")


def resolve_species(raw: str) -> Optional[str]:
    cleaned = _basic_clean(raw)
    if not cleaned:
        return None
    if cleaned in _SPECIES_ALIASES:
        return _SPECIES_ALIASES[cleaned]
    for tok in cleaned.split():
        if tok in _SPECIES_ALIASES:
            return _SPECIES_ALIASES[tok]
    return None


def _drug_in(entry_key: str, canonical: str) -> bool:
    """True if `canonical` is the entry's drug, or a member of its drug class."""
    return entry_key == canonical or canonical in _CLASSES.get(entry_key, ())


def _unknown_drug_alert(raw: str) -> Alert:
    return Alert(
        severity=UNVERIFIED,
        kind="lookup",
        drugs=[raw],
        message_en=(
            f'"{raw}" is NOT in the clinical database. No contraindication, '
            f"interaction or dose check has been performed for it. This is not a "
            f"statement that it is safe — check a current formulary manually."
        ),
        message_ar=(
            f'الدواء "{raw}" غير موجود في قاعدة البيانات السريرية. لم يتم إجراء أي '
            f"فحص لموانع الاستعمال أو التداخلات أو الجرعة. هذا لا يعني أنه آمن — "
            f"يجب المراجعة يدويًا في مرجع دوائي حديث."
        ),
    )


